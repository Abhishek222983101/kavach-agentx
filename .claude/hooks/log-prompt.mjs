#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const root = process.env.CLAUDE_PROJECT_DIR || process.cwd();

let raw = '';
process.stdin.setEncoding('utf8');
for await (const chunk of process.stdin) raw += chunk;

let input = {};
try {
  input = JSON.parse(raw);
} catch {
  process.exit(0);
}

const prompt = String(input.prompt || '').trim();
if (!prompt) process.exit(0);

const redact = (text) =>
  text
    .replace(/\b(sk-[A-Za-z0-9_-]{10,})\b/g, '[REDACTED_KEY]')
    .replace(/\b(ghp_[A-Za-z0-9]{20,})\b/g, '[REDACTED_KEY]')
    .replace(/\b(github_pat_[A-Za-z0-9_]{20,})\b/g, '[REDACTED_KEY]')
    .replace(/\b(AIza[0-9A-Za-z_-]{20,})\b/g, '[REDACTED_KEY]')
    .replace(/\b(xox[baprs]-[A-Za-z0-9-]{10,})\b/g, '[REDACTED_KEY]')
    .replace(/\b(AKIA[0-9A-Z]{16})\b/g, '[REDACTED_KEY]')
    .replace(/\b(gsk_[A-Za-z0-9]{20,})\b/g, '[REDACTED_KEY]')
    .replace(/\b(AC[0-9a-f]{32})\b/g, '[REDACTED_SID]')
    .replace(/\b[0-9]{8,10}:[A-Za-z0-9_-]{30,}\b/g, '[REDACTED_BOT_TOKEN]')
    .replace(/\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b/g, '[REDACTED_UUID]')
    .replace(/(password|passwd|secret|api[_-]?key|access[_-]?token|refresh[_-]?token)\s*[:=]\s*\S+/gi, '$1=[REDACTED]')
    .replace(/-----BEGIN [A-Z ]*PRIVATE KEY-----[\s\S]*?-----END [A-Z ]*PRIVATE KEY-----/g, '[REDACTED_PRIVATE_KEY]');

const clean = redact(prompt);
const capped = clean.length > 50000 ? clean.slice(0, 50000) + '\n\n[TRUNCATED AT 50,000 CHARACTERS]' : clean;

const now = new Date();
const stamp = now.toISOString().replace('T', ' ').slice(0, 16);
const session = String(input.session_id || 'unknown').slice(0, 8);

const rawDir = path.join(root, 'docs', '05-SESSIONS', 'raw');
fs.mkdirSync(rawDir, { recursive: true });

const jsonlPath = path.join(rawDir, 'prompts.jsonl');
fs.appendFileSync(
  jsonlPath,
  JSON.stringify({
    at: now.toISOString(),
    session,
    cwd: input.cwd || root,
    prompt: capped,
  }) + '\n'
);

const mdPath = path.join(root, 'docs', '05-SESSIONS', 'PROMPT-LOG.md');
const longestFence = (capped.match(/`+/g) || []).reduce((max, run) => Math.max(max, run.length), 0);
const fence = '`'.repeat(Math.max(3, longestFence + 1));
const entry = `\n## ${stamp} · session ${session}\n\n${fence}text\n${capped}\n${fence}\n\n`;

try {
  fs.appendFileSync(mdPath, entry);
} catch {
  fs.writeFileSync(
    mdPath,
    '# Raw prompt log\n\nAuto-captured by the Project Context Kit. Entries are appended in chronological order. Do not edit this file; the agent summarises it in `SESSION-LOG.md`.\n\n' +
      entry
  );
}

process.exit(0);
